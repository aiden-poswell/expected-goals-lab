def test_changing_held_out_rows_cannot_change_any_s05_output(world):
    clean = call(world)
    clean_text = report(world, clean)
    test_dates = held_out_dates(world["csv"], world["manifest"])

    def garble(lines):
        out = [lines[0]]
        for line in lines[1:]:
            cells = line.split(",") if line else []
            if cells and cells[column_index("match_datetime_utc")][:10] in test_dates:
                for name in (
                    "is_goal",
                    "distance_m",
                    "angle_rad",
                    "x_pct",
                    "y_pct",
                    "body_part_class",
                ):
                    cells[column_index(name)] = "GARBAGE"
            out.append(",".join(cells) if cells else line)
        return out

    rewrite_csv(world["csv"], world["manifest"], garble)
    # the split manifest recorded earlier names the old table hash, so refresh it
    old_split = json.loads(
        (world["split"] / "wyscout_split_manifest.json").read_text(encoding="utf-8")
    )
    old_split["input_csv_sha256"] = json.loads(world["manifest"].read_text(encoding="utf-8"))[
        "csv_sha256"
    ]
    (world["split"] / "wyscout_split_manifest.json").write_text(
        json.dumps(old_split), encoding="utf-8"
    )
    altered = call(world)

    assert altered.provenance["input_csv_sha256"] != clean.provenance["input_csv_sha256"]
    assert altered.leagues == clean.leagues
    assert altered.calibration == clean.calibration and altered.tally == clean.tally
    assert altered.raw_validation == clean.raw_validation and altered.raw_train == clean.raw_train
    assert altered.adjusted == clean.adjusted and altered.fitted_terms == clean.fitted_terms
    assert altered.illustrations == clean.illustrations
    assert altered.s04.scores == clean.s04.scores
    assert strip(report(world, altered)) == strip(clean_text)


# --- leagues, calibration and denominators ----------------------------------------------------


def test_five_league_groupings_match_an_independent_count(world):
    result = call(world)
    validation_ids = set(result.s04.parts["validation"].base.event_ids.tolist())
    truth = {}
    for row in world["rows"]:
        if row.event_id in validation_ids:
            shots, goals = truth.get(row.competition_id, (0, 0))
            truth[row.competition_id] = (shots + 1, goals + row.is_goal)

    assert [r["competition_id"] for r in result.leagues] == LEAGUE_IDS
    assert [r["name"] for r in result.leagues] == list(LEAGUE_NAMES.values())
    assert {r["competition_id"]: (r["shots"], r["goals"]) for r in result.leagues} == truth
    assert sum(r["shots"] for r in result.leagues) == len(validation_ids)
    assert all(r["diff_log_loss"] is not None for r in result.leagues)


def test_an_unverified_league_in_the_validation_rows_fails_closed(world, tmp_path):
    rows = s05_rows()
    late = [r for r in rows if r.eligible][-300:]
    rows = [dataclasses.replace(r, competition_id=999) if r in late[:60] else r for r in rows]
    csv_path, manifest_path, _ = write_s05_dataset(tmp_path / "bad", rows)
    folder = tmp_path / "bad_reports"
    s03, s04, split = write_committed_reports(csv_path, manifest_path, folder)
    with pytest.raises(ContractError, match="without a verified name"):
        run(csv_path, manifest_path, split, RESAMPLES, s03, s04, folder / "n.md", folder / "n2.md")


def test_calibration_bins_add_up_and_probabilities_are_valid(world):
    result = call(world)
    y = result.s04.parts["validation"].base.y
    for key in ("reference", "selected"):
        bins = result.calibration[key]
        assert sum(b["shots"] for b in bins) == len(y) and sum(b["goals"] for b in bins) == int(
            y.sum()
        )
        assert all(
            0.0 <= b["mean_prediction"] <= 1.0 and 0.0 <= b["low"] <= b["high"] <= 1.0 for b in bins
        )
        assert result.tally[key]["goals"] == int(y.sum()) and result.tally[key]["shots"] == len(y)
    for model in (REFERENCE, SELECTED):
        p = result.s04.predictions["validation"][model]
        assert ((p >= 0) & (p <= 1)).all()


