def test_first_screen_is_short_and_states_the_limits(world):
    text = report(world, call(world))
    finding = next(ln for ln in text.splitlines() if ln.startswith("**Finding.**"))
    sentences = re.split(r"(?<=[.)])\s+(?=[A-Z])", finding.replace("**Finding.** ", ""))
    assert len(sentences) == 3
    assert text.startswith("# ") and "**Question.**" in text and "**Limitation.**" in text
    assert "one season" in text.lower() and "has not been scored" in text
    for claim in ("outcome-blind", "entirely sealed", "deployable", "statistically significant"):
        assert claim not in text.lower()
    assert "has not been modelled or scored" in text and "indirectly inferable" in text
    assert "../" in text and ".png" in text  # links to the figures


