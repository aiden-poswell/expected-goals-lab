def test_nothing_data_like_can_be_tracked():
    try:
        listed = subprocess.run(
            ["git", "ls-files", "-co", "--exclude-standard"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        pytest.skip("not inside a git repository")
    published = {"results/final_test_summary.json"}  # the one published aggregate JSON
    bad = [
        f
        for f in listed
        if re.search(r"\.(zip|csv|json|parquet|pkl|part)$|^data/|\.venv|\.env", f)
        and f not in published
    ]
    assert bad == []


