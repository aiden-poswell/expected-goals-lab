def test_report_text_is_reproducible_and_figures_are_deterministic(world):
    first, second = call(world), call(world)
    assert strip(report(world, first)) == strip(report(world, second))
    a = make_figures(first, world["tmp"] / "a")
    b = make_figures(second, world["tmp"] / "b")
    assert [p.name for p in a] == [f"{s}.{e}" for s in FIGURE_STEMS for e in ("png", "svg")]
    for x, y in zip(a, b, strict=True):
        assert x.read_bytes() == y.read_bytes()
    for png, svg in zip(a[::2], a[1::2], strict=True):
        assert png.read_bytes()[:4] == b"\x89PNG" and ET.parse(svg).getroot().tag.endswith("svg")


