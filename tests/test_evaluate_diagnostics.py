RESAMPLES = 50


@pytest.fixture
def world(tmp_path):
    csv_path, manifest_path, rows = write_s05_dataset(tmp_path / "in")
    s03_report, s04_report, split_dir = write_committed_reports(
        csv_path, manifest_path, tmp_path / "reports"
    )
    return {
        "csv": csv_path,
        "manifest": manifest_path,
        "rows": rows,
        "s03": s03_report,
        "s04": s04_report,
        "split": split_dir,
        "tmp": tmp_path,
    }


def call(world, **kwargs):
    kwargs.setdefault("s03_report", world["s03"])
    kwargs.setdefault("s04_report", world["s04"])
    kwargs.setdefault("s04_protocol", world["tmp"] / "none.md")
    kwargs.setdefault("protocol", world["tmp"] / "none2.md")
    return run(world["csv"], world["manifest"], world["split"], RESAMPLES, **kwargs)


def strip(text: str) -> str:
    skipped = ("Generated by", "- Input table", "- Git commit")
    return "\n".join(ln for ln in text.splitlines() if not ln.startswith(skipped))


def report(world, result):
    return render_report(
        result, world["csv"], world["tmp"] / "r" / "model_diagnostics.md", world["tmp"] / "f"
    )


# --- S04 is reproduced from the unchanged factories -----------------------------------------


def test_s04_validation_numbers_are_reproduced_exactly_before_diagnostics(world):
    result = call(world)
    s04 = evaluate_nonlinear.evaluate_nonlinear(
        world["csv"],
        world["manifest"],
        world["split"],
        RESAMPLES,
        world["s03"],
        world["tmp"] / "x.md",
    )
    assert result.s04.scores == s04.scores  # exact equality, not just printed precision
    assert (
        dict(result.checks)[
            "Regenerated S04 validation numbers equal the committed S04 report "
            "(to printed precision)"
        ]
        == "pass"
    )
    assert result.s04.scores["validation"][REFERENCE].n == len(result.s04.parts["validation"])


def test_a_tampered_or_missing_s04_report_stops_the_run(world):
    tampered = (
        world["s04"]
        .read_text(encoding="utf-8")
        .replace(
            "| nonlinear_location_body_part |",
            "| nonlinear_location_body_part | 1 | 1 | 9.9999 | 9.99999 | 0.999 | X |",
            1,
        )
    )
    world["s04"].write_text(tampered, encoding="utf-8")
    with pytest.raises(ContractError, match="differs from the S04 report"):
        call(world)
    with pytest.raises(ContractError, match="cannot be reproduced"):
        call(world, s04_report=world["tmp"] / "absent.md")


