ALLOWED_HEADER_PHRASES = (
    "not a confirmed header",
    "mixes headers with other",
    "effect of heading",
    "heading as a skill",
)


def test_tag_403_is_never_called_a_confirmed_header_in_text_or_captions(world):
    result = call(world)
    text = report(world, result)
    first = evaluate_diagnostics.figure_inputs(result)
    texts = [text, *[str(first[k][f]) for k in first for f in ("headline", "subtitle", "caption")]]
    for chunk in texts:
        remaining = chunk.lower()
        for phrase in ALLOWED_HEADER_PHRASES:
            remaining = remaining.replace(phrase, "")
        assert "header" not in remaining and "heading" not in remaining, chunk[:200]
    assert "not a confirmed header" in text and "head/body" in text
    assert "association" in text.lower()
    assert "not a measured effect of changing how a shot is struck" in " ".join(text.split())


